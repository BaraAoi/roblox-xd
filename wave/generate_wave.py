def render_preview(obj_path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection

    v, f_tri, face_mtl = [], [], []
    mtl = None
    with open(obj_path, "r", encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("v "):
                v.append([float(x) for x in line.split()[1:4]])
            elif line.startswith("usemtl "):
                mtl = line.split()[1]
            elif line.startswith("f "):
                idx = [int(p.split("/")[0]) - 1 for p in line.split()[1:4]]
                f_tri.append(idx)
                face_mtl.append(mtl)

    v = np.array(v)
    # matplotlib draws the 3rd axis (plot-z) vertically, so map
    # model (x, y=up, z) -> plot (x, z, y) to keep the model upright
    vp = np.stack([v[:, 0], v[:, 2], v[:, 1]], axis=1)

    colors = {
        "WaveBody": (0.07, 0.72, 0.82),
        "Foam": (0.96, 0.98, 1.00),
        "Puddle": (0.03, 0.30, 0.40),
        "NeonRing": (0.25, 1.00, 0.95),
    }

    light = np.array([0.30, 0.65, 0.70])
    light = light / np.linalg.norm(light)

    fig = plt.figure(figsize=(15, 7.2), dpi=110)
    panels = [(4, 90, "Front view (curl silhouette)"), (16, 35, "Front 3/4 view")]
    for panel, (elev, azim, title) in enumerate(panels):
        ax = fig.add_subplot(1, 2, panel + 1, projection="3d")
        polys, facecolors = [], []
        for tri, m in zip(f_tri, face_mtl):
            p = vp[tri]
            nrm = np.cross(p[1] - p[0], p[2] - p[0])
            ln = np.linalg.norm(nrm)
            nrm = nrm / ln if ln > 0 else nrm
            base = np.array(colors.get(m, (0.7, 0.7, 0.7)))
            lam = 0.42 + 0.58 * abs(float(np.dot(nrm, light)))
            polys.append(p)
            facecolors.append(tuple(np.clip(base * lam, 0, 1)))
        coll = Poly3DCollection(polys, facecolors=facecolors, edgecolors="none")
        ax.add_collection3d(coll)
        ax.set_xlim(-6, 6.1)
        ax.set_ylim(-5.3, 5.3)
        ax.set_zlim(0, 8.6)
        ax.set_box_aspect((12.1, 10.6, 8.6))
        ax.view_init(elev=elev, azim=azim)
        ax.set_title(title, fontsize=11, color="#cfe9ee")
        ax.set_axis_off()
    fig.suptitle("Stylized neon wave for Roblox - smooth shaded", fontsize=13, color="#cfe9ee")
    fig.patch.set_facecolor("#08131a")
    fig.tight_layout()
    fig.savefig(PREVIEW_PATH, bbox_inches="tight", facecolor="#08131a")
    plt.close(fig)


def main():
    builder = ObjBuilder()

    spine_xy, normal, h = build_body(builder)
    build_foam(builder, spine_xy, normal, h)
    build_puddle(builder)
    build_neon_ring(builder)

    n_verts, n_faces = builder.stats()
    builder.write(OBJ_PATH, "neon_wave.mtl")
    with open(MTL_PATH, "w", encoding="utf-8") as f:
        f.write(MTL_TEXT)

    print(f"OBJ written: {OBJ_PATH}")
    print(f"MTL written: {MTL_PATH}")
    print(f"vertices: {n_verts}  triangles: {n_faces}")

    arr = np.array(builder.verts)
    lo, hi = arr.min(axis=0), arr.max(axis=0)
    print(f"bbox min: {lo.round(2)}  max: {hi.round(2)}")
    print(f"size (studs): width {hi[0]-lo[0]:.2f}, height {hi[1]-lo[1]:.2f}, depth {hi[2]-lo[2]:.2f}")

    render_preview(OBJ_PATH)
    print(f"Preview written: {PREVIEW_PATH}")


if __name__ == "__main__":
    main()
