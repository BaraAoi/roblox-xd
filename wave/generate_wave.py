    panels = [(4, 90, "Side view (breaking profile)"), (17, 30, "Front 3/4 view")]
    for panel, (elev, azim, title) in enumerate(panels):
        ax = fig.add_subplot(1, 2, panel + 1, projection="3d")
        polys, facecolors = [], []
        for tri, m in zip(f_tri, face_mtl):
            p = vp[tri]
            nrm = np.cross(p[1] - p[0], p[2] - p[0])
            ln = np.linalg.norm(nrm)
            nrm = nrm / ln if ln > 0 else nrm
            base = np.array(colors.get(m, (0.7, 0.7, 0.7)))
            lam = 0.42 + 0.58 * abs(float(np.dot(nrm, light)))
            polys.append(p)
            facecolors.append(tuple(np.clip(base * lam, 0, 1)))
        coll = Poly3DCollection(polys, facecolors=facecolors, edgecolors="none")
        ax.add_collection3d(coll)
        ax.set_xlim(-5.9, 5.9)
        ax.set_ylim(-5.0, 5.0)
        ax.set_zlim(0, 8.0)
        ax.set_box_aspect((11.8, 10.0, 8.0))
        ax.view_init(elev=elev, azim=azim)
        ax.set_title(title, fontsize=11, color="#cfe9ee")
        ax.set_axis_off()
    fig.suptitle("Stylized neon wave for Roblox - smooth shaded", fontsize=13, color="#cfe9ee")
    fig.patch.set_facecolor("#08131a")
    fig.tight_layout()
    fig.savefig(PREVIEW_PATH, bbox_inches="tight", facecolor="#08131a")
    plt.close(fig)


